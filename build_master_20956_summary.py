def classify_one(name, text):
    n = (name or '').lower()
    t = (text or '').lower()
    for cat, pats in RULES.items():
        for p in pats:
            if re.search(p, n) or re.search(p, t):
                return cat
    return 'Неопределенные бренды (на проверке)'

