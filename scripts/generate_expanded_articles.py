def markdown_to_html(md: str, author_quote: str, cases: list[dict]) -> str:
    lines = md.strip().split("\n")
    html_parts = []
    in_list = False
    list_type = "ul"
    
    case_idx = 0

    for line in lines:
        line_str = line.strip()
        if not line_str:
            if in_list:
                html_parts.append(f"</{list_type}>")
                in_list = False
            continue

        # Headers
        if line_str.startswith("### "):
            if in_list:
                html_parts.append(f"</{list_type}>")
                in_list = False
            h_text = line_str[4:].strip()
            html_parts.append(f"<h3>{h_text}</h3>")
            continue
        elif line_str.startswith("## "):
            if in_list:
                html_parts.append(f"</{list_type}>")
                in_list = False
            h_text = line_str[3:].strip()
            html_parts.append(f"<h2>{h_text}</h2>")
            continue

        # Quote embed
        if line_str == "> [QUOTE]" or line_str.startswith("> [QUOTE]"):
            if in_list:
                html_parts.append(f"</{list_type}>")
                in_list = False
            q_text = author_quote
            html_parts.append(f'<blockquote class="mt-article-quote"><p>{q_text}</p><cite>Основатель платформы Молния</cite></blockquote>')
            continue

        # Case embed start
        if line_str.startswith("> [CASE]"):
            if in_list:
                html_parts.append(f"</{list_type}>")
                in_list = False
            c_head = line_str[8:].strip()
            # find corresponding case body
            c_body = cases[case_idx]["text"] if case_idx < len(cases) else ""
            case_idx += 1
            html_parts.append(f'<div class="callout success"><div class="callout-title">⚡ {c_head}</div><p>{c_body}</p></div>')
            continue

        if line_str == "> [CASE_BODY]" or line_str.startswith("> [CASE_BODY]"):
            # already processed in [CASE]
            continue

        # Lists
        if line_str.startswith("* ") or line_str.startswith("- "):
            if not in_list:
                html_parts.append("<ul>")
                in_list = True
                list_type = "ul"
            item_text = line_str[2:].strip()
            # format **Bold:** text
            item_text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", item_text)
            html_parts.append(f"  <li>{item_text}</li>")
            continue

        if re.match(r"^\d+\.\s+", line_str):
            if not in_list:
                html_parts.append("<ol>")
                in_list = True
                list_type = "ol"
            item_text = re.sub(r"^\d+\.\s+", "", line_str).strip()
            item_text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", item_text)
            html_parts.append(f"  <li>{item_text}</li>")
            continue

        # Regular paragraph
        if in_list:
            html_parts.append(f"</{list_type}>")
            in_list = False

        p_text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", line_str)
        p_text = re.sub(r"«(.+?)»", r"«\1»", p_text)
        html_parts.append(f"<p>{p_text}</p>")

    if in_list:
        html_parts.append(f"</{list_type}>")

    return "\n".join(html_parts)


