def classify_two_tier(name, text):
    n = (name or '').lower()
    t = (text or '').lower()
    
    # 1. Сначала ищем жесткие маркеры в названии
    for sector, patterns in SECTOR_RULES.items():
        for p in patterns:
            if re.search(p, n):
                return sector, 'High (по названию)'
                
    # 2. Ищем предметные маркеры в тексте отзыва (исключая общие слова вроде 'сервис')
    if re.search(r'собак|кошк|груминг|шерст|питом|лапк|стрижка собак|ветеринар', t):
        return 'Животные / Груминг / Вет', 'High (по тексту отзыва)'
    if re.search(r'автомойк|детейл|полировк|машин|автомобил|заказ-наряд|шиномонтаж', t):
        return 'Автобизнес / Детейлинг / СТО', 'High (по тексту отзыва)'
    if re.search(r'пациент|зуб|стоматолог|врач|лечени|прием врача|анализы', t):
        return 'Здоровье / Стоматология / Медицина', 'High (по тексту отзыва)'
    if re.search(r'массаж|массажист|спа-программ|хаммам', t):
        return 'СПА и Массаж', 'High (по тексту отзыва)'
    if re.search(r'тренировк|зал|спорт|йог|растяжк|абонемент|групповые занятия', t):
        return 'Фитнес / Спорт / Йога', 'High (по тексту отзыва)'
    if re.search(r'стрижк|окрашиван|блонд|маникюр|педикюр|ресниц|бров|эпил|депил|клиентк', t):
        return 'Бьюти / Салоны красоты (явные маркеры)', 'High (по тексту отзыва)'
    if re.search(r'заняти|ученик|урок|курс|дети|ребенок|родител', t):
        return 'Образование / Курсы / Дети', 'High (по тексту отзыва)'
        
    # 3. Если нет жестких маркеров — помечаем как НЕОПРЕДЕЛЕННОЕ (на отдельный лист!)
    return 'Неопределено (Требует проверки)', 'Uncertain'
